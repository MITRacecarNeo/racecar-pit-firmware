"""Write the git build stamp header and print its include flag; PlatformIO runs it.

The commit, dirty flag and label go into BUILD_INFO_DIR/build_info.h, read only by
src/version.h. A new commit then recompiles the files that include it, not the
Teensy core and libraries, which a changed global -D flag would rebuild. The header
is rewritten only when its content changes.
"""

from __future__ import annotations

from pathlib import Path
import re
import subprocess

# Internal commit labels: "[v0.9.0.3-pcb] scope: summary".
LABEL = re.compile(r"^\[(v\d+\.\d+\.\d+\.\d+-pcb)\]")


def _git(*args: str) -> str:
    try:
        out = subprocess.run(["git", *args], capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return ""
    return out.stdout.strip()


def latest_label(subjects: str) -> str:
    """Label of the newest labeled subject in `git log` order, or "dev"."""
    for subject in subjects.splitlines():
        match = LABEL.match(subject)
        if match:
            return match.group(1)
    return "dev"


BUILD_INFO_DIR = Path(".pio") / "build_info"


def header_text(commit: str, dirty: int, label: str) -> str:
    return (
        "#pragma once\n"
        "// Generated by scripts/build_flags.py; not tracked.\n"
        f"#define FW_GIT_HASH {commit}\n"
        f"#define FW_GIT_DIRTY {dirty}\n"
        f"#define FW_LABEL {label}\n"
    )


def write_if_changed(path: Path, text: str) -> bool:
    """Write text to path unless it already holds it; True when written."""
    if path.is_file() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def build_flags(out_dir: Path = BUILD_INFO_DIR) -> str:
    commit = _git("rev-parse", "--short=7", "HEAD") or "unknown"
    dirty = 1 if _git("status", "--porcelain", "--untracked-files=no") else 0
    label = latest_label(_git("log", "--format=%s", "-n", "200"))
    write_if_changed(out_dir / "build_info.h", header_text(commit, dirty, label))
    return f"-I{out_dir}"


if __name__ == "__main__":
    print(build_flags())
